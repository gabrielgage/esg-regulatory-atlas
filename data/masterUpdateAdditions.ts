const src = (label: string, url: string, type: SourceLink["type"] = "primary"): SourceLink => ({
  label,
  url,
  type
});

type MasterRecordInput = Omit<
  Regulation,
  "topic" | "valueChainImpact" | "confidence" | "confidenceLevel" | "dataQualityStatus" | "lastReviewed" | "nextReviewDate" | "sourceUrls"
> &
  Partial<Pick<Regulation, "topic" | "valueChainImpact" | "confidenceLevel" | "dataQualityStatus" | "lastReviewed" | "nextReviewDate" | "sourceUrls">>;

const masterRecord = (record: MasterRecordInput): Regulation => {
  const confidenceLevel: Confidence = record.confidenceLevel || "medium";
  const dataQualityStatus: DataQualityStatus = record.dataQualityStatus || "needs_review";

  return {
    recordType: "regulation",
    legalForce: "mandatory",
    displayTier: "expanded",
    atlasGranularity: "parent",
    aliases: [],
    sourceSystem: "Manual Research",
    sourceConfidence: confidenceLevel,
    lastVerified: record.lastReviewed || REVIEWED,
    clientRelevanceCategory: "potentially-direct",
    marketMaturityScore: "basic",
    monetizationTier: "lead-generation",
    ...record,
    topic: record.topic || record.topics[0],
    valueChainImpact: record.valueChainImpact || record.valueChain,
    sourceUrls: record.sourceUrls || [],
    confidence: confidenceLevel,
    confidenceLevel,
    dataQualityStatus,
    lastReviewed: record.lastReviewed || REVIEWED,
    nextReviewDate: record.nextReviewDate || NEXT_REVIEW
  };
};

